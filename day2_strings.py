name = "Enes Mumeita"

print("Name:", name)

# Indexing
print("\n--- Indexing ---")
print("First character:", name[0])
print("Last character:", name[-1])

# Slicing
print("\n--- Slicing ---")
print("First 4 characters:", name[:4])
print("Last 4 characters:", name[-4:])

# String methods
print("\n--- String Methods ---")
print("Uppercase:", name.upper())
print("Lowercase:", name.lower())

# Length
print("\n--- Length ---")
print("Number of characters:", len(name))

# Searching
print("\n--- Searching ---")
print("Is 'Enes' in the name?", "Enes" in name)
print("Is 'Python' in the name?", "Python" in name)